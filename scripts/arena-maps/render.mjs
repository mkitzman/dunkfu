// Generate arena map art for the box score scoreboard.
//
//   npm run arena-maps            all 30 arenas
//   npm run arena-maps GSW LAL    just these
//
// Needs Google Chrome installed (driven via puppeteer-core). Writes
// src/assets/maps/<abbr>.jpg and regenerates src/data/arenaMaps.js.
// Map data © OpenStreetMap contributors, tiles © OpenMapTiles via OpenFreeMap;
// the site footer carries the attribution.

import fs from 'node:fs'
import http from 'node:http'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import puppeteer from 'puppeteer-core'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(HERE, '../..')
const OUT = path.join(ROOT, 'src/assets/maps')
const CHROME = process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'
const ZOOM = 14.3
const W = 1800, H = 448 // CSS px; rendered at 1.5x

const config = JSON.parse(fs.readFileSync(path.join(HERE, 'arenas.json'), 'utf8'))
const all = Object.keys(config).filter(k => !k.startsWith('_'))
const only = process.argv.slice(2).map(s => s.toUpperCase())
const teams = only.length ? all.filter(a => only.includes(a)) : all

// Serve the page plus MapLibre from node_modules.
const files = {
  '/page.html': path.join(HERE, 'page.html'),
  '/maplibre-gl.js': path.join(ROOT, 'node_modules/maplibre-gl/dist/maplibre-gl.js'),
  '/maplibre-gl.css': path.join(ROOT, 'node_modules/maplibre-gl/dist/maplibre-gl.css'),
}
const server = http.createServer((req, res) => {
  const f = files[new URL(req.url, 'http://x').pathname]
  if (!f) { res.writeHead(404); return res.end() }
  res.writeHead(200, { 'content-type': f.endsWith('.html') ? 'text/html' : f.endsWith('.css') ? 'text/css' : 'text/javascript' })
  fs.createReadStream(f).pipe(res)
}).listen(0)
const port = server.address().port

fs.mkdirSync(OUT, { recursive: true })
const browser = await puppeteer.launch({ executablePath: CHROME, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
const meta = fs.existsSync(path.join(HERE, 'meta.json')) ? JSON.parse(fs.readFileSync(path.join(HERE, 'meta.json'), 'utf8')) : {}

for (const abbr of teams) {
  const t = config[abbr]
  const page = await browser.newPage()
  await page.setViewport({ width: W, height: H, deviceScaleFactor: 1.5 })
  const qs = new URLSearchParams({ lat: t.lat, lon: t.lon, zoom: t.zoom ?? ZOOM, base: t.base, accent: t.accent })
  await page.goto(`http://localhost:${port}/page.html?${qs}`)
  await page.waitForFunction(() => document.title === 'DONE', { timeout: 90000 })
  const { deep } = await page.evaluate(() => window.mapColors)
  await page.screenshot({ path: path.join(OUT, `${abbr.toLowerCase()}.jpg`), type: 'jpeg', quality: 62, clip: { x: 0, y: 0, width: W, height: H } })
  meta[abbr] = { baseColor: deep, pin: t.accent }
  console.log(`${abbr} ${t.arena}`)
  await page.close()
}
await browser.close()
server.close()
fs.writeFileSync(path.join(HERE, 'meta.json'), JSON.stringify(meta, null, 1) + '\n')

// src/data/arenaMaps.js: every arena that has an image. Maps are centered on
// the arena, so focal is the middle of the image.
const have = all.filter(a => fs.existsSync(path.join(OUT, `${a.toLowerCase()}.jpg`)) && meta[a])
const js = `// Generated by scripts/arena-maps/render.mjs — do not edit by hand.
// Map art behind the box score scoreboard, keyed by home team.
//   src        image (rendered 1800px wide)
//   aspect     image height / width
//   baseColor  card color under the map (the map's water color)
//   focal      arena position as a fraction of the image
//   pin        pin + radar color (team accent)
${have.map(a => `import ${a.toLowerCase()} from '../assets/maps/${a.toLowerCase()}.jpg'`).join('\n')}

const aspect = ${H} / ${W}
const focal = { x: 0.5, y: 0.5 }

export default {
${have.map(a => `  ${a}: { src: ${a.toLowerCase()}, aspect, baseColor: '${meta[a].baseColor}', focal, pin: '${meta[a].pin}' },`).join('\n')}
}
`
fs.writeFileSync(path.join(ROOT, 'src/data/arenaMaps.js'), js)
console.log(`${teams.length} rendered; arenaMaps.js lists ${have.length} arenas.`)
